PREVIOUS_RUN_SUFFIX = ".prev"


def begin_fresh_run(path: Path) -> None:
    """A Python model of `er_game_base::log::begin_fresh_run`, called once per (process, path).

    Kept honest by `check_model_matches_rust()`: if the Rust stops removing the stale `.prev`
    unconditionally, or stops renaming, the selftest goes red instead of simulating fiction.
    """
    previous = path.with_name(path.name + PREVIOUS_RUN_SUFFIX)
    previous.unlink(missing_ok=True)
    if path.exists():
        path.rename(previous)
    path.write_text("build git=<identity line>\n", encoding="utf-8")


def check_model_matches_rust() -> list[str]:
    source = REPO_ROOT / "crates/er-game-base/src/log.rs"
    text = source.read_text(encoding="utf-8", errors="replace")
    problems = []
    for needed in (
        'pub const PREVIOUS_RUN_SUFFIX: &str = ".prev";',
        "let _ = fs::remove_file(&previous);",
        "let _ = fs::rename(path, &previous);",
        ".truncate(true)",
    ):
        if needed not in text:
            problems.append(
                f"er-game-base/src/log.rs no longer contains {needed!r}; the rotation model in "
                f"this script is simulating behaviour the writer does not have"
            )
    return problems


def simulate_run(
    game_dir: Path,
    artifact_dir: Path | None,
    lines: str,
    names: tuple[str, ...] = ("er-quickload-continue-trace.log",),
) -> None:
    """One launch. `artifact_dir=None` is the unredirected case: the artifact lands in GAME_DIR.

    `names` defaults to the one file the reported bug was about; pass every knob's default name to
    model a whole run's evidence rather than a single log.
    """
    target_dir = artifact_dir if artifact_dir is not None else game_dir
    target_dir.mkdir(parents=True, exist_ok=True)
    for name in names:
        path = target_dir / name
        begin_fresh_run(path)
        with path.open("a", encoding="utf-8") as handle:
            handle.write(lines)


def selftest() -> int:
    import tempfile

    ok = True

    def check(condition: bool, label: str) -> None:
        nonlocal ok
        if not condition:
            ok = False
        print(("  ok   " if condition else "  FAIL ") + label)

    check(not check_model_matches_rust(), "the rotation model still matches er-game-base's writer")
    for problem in check_model_matches_rust():
        print("         " + problem)

    stale = verify_no_knob_table()
    check(not stale, "every hand-written inventory row still describes the code")
    for problem in stale:
        print("         " + problem)

    knobs = discover_knobs()
    envs = {knob.env for knob in knobs}

    shared = verify_shared_table(knobs)
    check(not shared, "the shared Python env table redirects every knob the DLLs honour")
    for problem in shared:
        print("         " + problem)
    check(
        len(shared_table_knobs()) == len(knobs),
        f"the shared table is parsed and complete ({len(shared_table_knobs())} of {len(knobs)})",
    )

    recovered = verify_recovered_knobs(knobs)
    check(
        not recovered,
        f"the {len(RECOVERED_KNOBS)} artifacts that had no knob are still redirectable",
    )
    for problem in recovered:
        print("         " + problem)
    # Non-VACUITY. The check above must be capable of failing, or it is decoration on the one fact
    # this whole task turned on. Drop a knob and it must go red.
    check(
        len(verify_recovered_knobs([k for k in knobs if k.default_name != "er-reload-trace.log"]))
        == 1,
        "losing a recovered knob is a FAILURE, not a smaller gap count",
    )
    # Non-vacuity: the parse must find the knobs this bug was actually about. A regex that silently
    # stops matching would otherwise report a clean tree over a broken one.
    check(len(knobs) >= 6, f"the knob table is parsed out of the Rust sources ({len(knobs)} found)")
    for expected in (
        "ER_QUICKLOAD_TRACE_CONTINUE_PATH",
        "ER_QUICKLOAD_AUTOLOAD_DEBUG_PATH",
        "ER_QUICKLOAD_INPUT_TRACE_PATH",
        "ER_QUICKLOAD_TELEMETRY_PATH",
    ):
        check(expected in envs, f"{expected} is discovered from the code")
    check(
        "ER_QUICKLOAD_COMMAND_PATH" not in envs,
        "an INPUT channel is not demanded of launchers as if it were evidence",
    )
    by_env = {knob.env: knob for knob in knobs}
    check(
        by_env["ER_QUICKLOAD_TRACE_CONTINUE_PATH"].default_name
        == "er-quickload-continue-trace.log",
        "the knob's GAME_DIR default filename is read from its own resolver",
    )

    launchers = discover_launchers()
    names = {launcher.name for launcher in launchers}
    check(len(launchers) >= 8, f"launchers are discovered by their launch command ({len(launchers)})")
    for expected in (
        "run-me3-product-smoke.sh",
        "run-product-continue-direct-probe.sh",
        "er-smoke-driver.sh",
    ):
        check(expected in names, f"{expected} is recognised as a launcher")
    check(
        "er-artifact-redirect-audit.py" not in names,
        "the audit does not audit itself",
    )

    # A launcher missing a knob must be reported, and the same launcher with an exemption must not.
    synthetic = Launcher(path=Path("synthetic.sh"), sets=set())
    check(
        len(audit(knobs, [synthetic])) == len(knobs),
        "a launcher that redirects nothing is reported once per knob",
    )
    synthetic_exempt = Launcher(
        path=Path("synthetic.sh"),
        sets=set(),
        exempt={knob.env: "stated reason" for knob in knobs},
    )
    check(
        audit(knobs, [synthetic_exempt]) == [],
        "a STATED exemption silences the gap (it is declared, not hidden)",
    )
    synthetic_full = Launcher(path=Path("synthetic.sh"), sets=set(envs))
    check(audit(knobs, [synthetic_full]) == [], "a launcher that redirects everything is clean")
    bad_delegate = Launcher(path=Path("synthetic.sh"), delegates_to="scripts/does-not-exist.sh")
    check(
        len(audit(knobs, [bad_delegate])) == 1,
        "a delegates-to pointing at nothing is a failure, not a free pass",
    )

    # The swept launchers must stay swept. Frozen by name, because a regression here is silent:
    # dropping one env line puts that artifact back in the single-slot game directory and nothing
    # else in the repo notices.
    clean = {
        launcher.name
        for launcher in launchers
        if not launcher.is_library
        and not launcher.delegates_to
        and not launcher.single_slot
        and not (set(envs) - launcher.sets - set(launcher.exempt))
    }
    for expected in (
        "er-run-branch.py",
        "capture-er-frame.sh",
        "er-smoke-driver.sh",
        "run-me3-product-smoke.sh",
        "run-product-continue-direct-probe.sh",
        "run-windows-proof-render-smoke.sh",
        # Added with the two loading-portrait knobs (2026-08-31): the smoke that reads them is the
        # one launcher whose pass bar depends on finding those exact two files.
        "run-portrait-dll-standalone-smoke.sh",
        # Twenty-plus launches in one `--all` sweep, each of which used to write over the last.
        "sweep-dll-1170-runtime.py",
    ):
        check(expected in clean, f"{expected} still redirects every artifact out of GAME_DIR")

    # The stated single-slot launcher. The shipped end-user helper deliberately redirects nothing,
    # and until 2026-08-31 that was invisible here -- the generator writes its `me3 launch` inside
    # a heredoc string, so no launch shape matched and it appeared in no report at all. Absence
    # reads as compliance. It is now a declared exemption with a reason, which is a different thing
    # from clean and must keep printing as such.
    by_name = {launcher.name: launcher for launcher in launchers}
    shipped = by_name.get("build-user-release-package.py")
    check(shipped is not None, "the shipped end-user launcher generator is discovered at all")
    check(
        shipped is not None and bool(shipped.single_slot) and len(shipped.single_slot) > 40,
        "it declares single-slot WITH a reason, not a bare marker",
    )
    check(
        shipped is not None and shipped.name not in clean,
        "a stated single-slot launcher is NOT counted among the ones that redirect everything",
    )
    # Non-vacuity: the exemption must silence the gap it declares, and only for the declarer.
    stated = Launcher(path=Path("synthetic.sh"), single_slot="stated reason")
    undeclared = Launcher(path=Path("synthetic-2.sh"))
    check(
        audit(knobs, [stated]) == [] and gap_keys(knobs, [stated]) == [],
        "a stated single-slot launcher raises no gap",
    )
    check(
        len(gap_keys(knobs, [undeclared])) == len(knobs),
        "...and an UNSTATED one still raises one per knob, so the marker is what does the work",
    )

    # The backlog is empty, and that has to be proven rather than assumed. It held 98 rows across
    # 13 launchers until 2026-08-31. A baseline that silently absorbed everything would turn this
    # audit into a no-op, so an empty file is only acceptable while the strict audit -- the one that
    # ignores the baseline entirely -- also comes back with nothing.
    recorded = read_baseline()
    live_gaps = gap_keys(knobs, launchers)
    check(
        not recorded and not live_gaps,
        f"no launcher leaks an artifact into GAME_DIR ({len(live_gaps)} live gap(s), "
        f"{len(recorded)} recorded)",
    )
    for key in sorted(live_gaps)[:20]:
        print("         " + key)
    check(
        all(row.split()[0] not in clean for row in recorded),
        "no launcher is both baselined and clean -- a stale row would hide a real regression",
    )
    check(
        "synthetic-new-launcher.sh ER_QUICKLOAD_TELEMETRY_PATH" not in recorded
        and bool(
            [
                key
                for key in gap_keys(
                    knobs, [Launcher(path=Path("synthetic-new-launcher.sh"))]
                )
                if key not in recorded
            ]
        ),
        "a launcher that is not in the baseline still produces NEW gaps, so drift fails",
    )

    # ---------------------------------------------------------------------------------------
    # Two consecutive runs. The whole point, reduced to something that needs no game.
    # ---------------------------------------------------------------------------------------
    with tempfile.TemporaryDirectory() as raw:
        root = Path(raw)
        game_dir = root / "Game"
        game_dir.mkdir()

        # (a) UNREDIRECTED, the bug. Run 1 writes into GAME_DIR; run 2 rotates it to `.prev`;
        #     run 3 destroys it outright.
        simulate_run(game_dir, None, "RUN-1 EVIDENCE\n")
        simulate_run(game_dir, None, "RUN-2 EVIDENCE\n")
        live = (game_dir / "er-quickload-continue-trace.log").read_text(encoding="utf-8")
        prev = (game_dir / "er-quickload-continue-trace.log.prev").read_text(encoding="utf-8")
        check("RUN-2 EVIDENCE" in live, "unredirected: run 2's evidence is the live file")
        check("RUN-1 EVIDENCE" in prev, "unredirected: run 1 survives ONE run, as `.prev`")
        simulate_run(game_dir, None, "RUN-3 EVIDENCE\n")
        prev = (game_dir / "er-quickload-continue-trace.log.prev").read_text(encoding="utf-8")
        check(
            "RUN-1 EVIDENCE" not in prev and "RUN-2 EVIDENCE" in prev,
            "unredirected: run 1 is GONE after the second following launch -- the reported bug",
        )

        # (b) the harness `rm -f`, which is worse: it drops two generations at once, because
        #     `begin_fresh_run` removes a stale `.prev` when the live file is absent.
        (game_dir / "er-quickload-continue-trace.log").unlink()
        simulate_run(game_dir, None, "RUN-4 EVIDENCE\n")
        check(
            not (game_dir / "er-quickload-continue-trace.log.prev").exists(),
            "a pre-launch `rm -f` of the live file destroys the surviving `.prev` too",
        )

        # (c) redirected, the fix. Two runs, two directories, nothing shared, nothing lost.
        run_one = root / "artifacts" / "run-1"
        run_two = root / "artifacts" / "run-2"
        simulate_run(game_dir, run_one, "RUN-1 EVIDENCE\n")
        simulate_run(game_dir, run_two, "RUN-2 EVIDENCE\n")
        first = (run_one / "er-quickload-continue-trace.log").read_text(encoding="utf-8")
        second = (run_two / "er-quickload-continue-trace.log").read_text(encoding="utf-8")
        check(
            "RUN-1 EVIDENCE" in first and "RUN-2 EVIDENCE" in second,
            "redirected: BOTH runs' evidence is readable after the second run",
        )
        check(
            not (run_one / "er-quickload-continue-trace.log.prev").exists(),
            "redirected: run 1's file was never rotated, because run 2 never touched its path",
        )

        # (d) a crashed or killed run. Nothing runs at teardown -- no copy, no reaper, no trap.
        #     Redirected, everything written before the crash is already in the right place.
        run_three = root / "artifacts" / "run-3"
        simulate_run(game_dir, run_three, "RUN-3 PARTIAL EVIDENCE, then SIGKILL\n")
        # ...and the next run starts, with no cleanup of any kind having happened.
        run_four = root / "artifacts" / "run-4"
        simulate_run(game_dir, run_four, "RUN-4 EVIDENCE\n")
        crashed = (run_three / "er-quickload-continue-trace.log").read_text(encoding="utf-8")
        check(
            "RUN-3 PARTIAL EVIDENCE" in crashed,
            "a crashed run's partial evidence survives the next launch with no teardown step",
        )

        # (e) the whole inventory, not one log. The counter this task is scored on is "how many of
        #     a run's artifacts can the next launch destroy", and the answer has to be zero for
        #     every row of the table, not for the one file the original bug happened to be about.
        #     Three launches -- two normal, one killed mid-write with no teardown of any kind --
        #     and then every artifact of all three is read back.
        every = tuple(knob.default_name for knob in knobs)
        first, second, killed = (root / "all" / part for part in ("run-1", "run-2", "run-3"))
        simulate_run(game_dir, first, "RUN-1 EVIDENCE\n", every)
        simulate_run(game_dir, second, "RUN-2 EVIDENCE\n", every)
        simulate_run(game_dir, killed, "RUN-3 PARTIAL, then SIGKILL\n", every)
        # ...and a fourth launch starts on top of all of it, having cleaned up nothing.
        simulate_run(game_dir, root / "all" / "run-4", "RUN-4 EVIDENCE\n", every)
        destroyed = [
            f"{directory.name}/{name}"
            for directory, marker in (
                (first, "RUN-1 EVIDENCE"),
                (second, "RUN-2 EVIDENCE"),
                (killed, "RUN-3 PARTIAL"),
            )
            for name in every
            if marker not in (directory / name).read_text(encoding="utf-8")
        ]
        check(
            not destroyed,
            f"all {len(every)} artifacts of THREE prior runs (one of them killed) are still "
            f"readable after a fourth launch -- {len(destroyed)} destroyable",
        )
        for entry in destroyed[:10]:
            print("         destroyed: " + entry)
        # Non-vacuity, on the exact pairs the last two sessions added: the same three launches
        # UNREDIRECTED must lose them, or the check above is proving nothing. Each pair is named
        # rather than folded into one loop over `every`, because these are the artifacts whose
        # knobs are newest and therefore the ones a careless revert would take back out.
        for label, pair in (
            (
                "the portrait pair",
                ("er-loading-portrait.log", "er-loading-portrait-crash-log.txt"),
            ),
            (
                "the save-census pair",
                ("er-save-disable.log", "er-save-disable-telemetry.json"),
            ),
        ):
            for marker in ("RUN-1 EVIDENCE", "RUN-2 EVIDENCE", "RUN-3 EVIDENCE"):
                simulate_run(game_dir, None, marker + "\n", pair)
            check(
                all(
                    "RUN-1 EVIDENCE"
                    not in (game_dir / name).read_text(encoding="utf-8")
                    and "RUN-1 EVIDENCE"
                    not in (game_dir / (name + PREVIOUS_RUN_SUFFIX)).read_text(encoding="utf-8")
                    for name in pair
                ),
                f"...and UNREDIRECTED, {label} loses run 1 after two more launches",
            )

    # ---------------------------------------------------------------------------------------
    # The reader half, which the redirect makes dangerous.
    #
    # Once nothing deletes the game-directory copy, it sits there complete and readable -- the
    # previous run's file. A monitor that resolves by existence at t=0 binds to it, counts its
    # lines, and scores a finished run as this one's; and because a stale file's mtime never
    # changes, a freshness check downstream then calls a perfectly healthy game frozen. Measured
    # 2026-08-31: a watcher did exactly this, declared world-stable at elapsed 0.0 s and tore down
    # a game that had not finished booting. So the mtime floor is not a refinement, it is the
    # other half of the fix, and it is exercised here in all four states a reader can meet.
    #
    # `run-save-census-probe.sh resolve` is the shell path, not a re-implementation of the Python
    # one: the launcher passes its redirects with an `env VAR=... me3` prefix, which never enters
    # the launcher's own environment, so its reader has to be handed the run directory explicitly.
    # Driving the real subcommand is what proves that wiring, quoting and argument order included.
    # ---------------------------------------------------------------------------------------
    import os
    import subprocess

    # The shared table lives beside this script; `sys.path[0]` already points there when it is run
    # as a script, but say so explicitly so the selftest survives being imported from elsewhere.
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    from er_artifact_env import resolve_artifact

    probe = SCRIPTS / "run-save-census-probe.sh"
    with tempfile.TemporaryDirectory() as raw:
        root = Path(raw)
        game_dir, run_dir = root / "Game", root / "run-1"
        game_dir.mkdir()
        run_dir.mkdir()
        launch = 1_000_000.0
        stale, fresh = launch - 600, launch + 1

        def write(path: Path, body: str, mtime: float) -> Path:
            path.write_text(body, encoding="utf-8")
            os.utime(path, (mtime, mtime))
            return path

        def resolved(name: str) -> str:
            out = subprocess.run(
                ["bash", str(probe), "resolve", name, str(game_dir), str(run_dir), str(launch)],
                capture_output=True,
                text=True,
                check=False,
                timeout=30,
            )
            return out.stdout.strip()

        name = "er-save-disable-telemetry.json"
        # (1) redirect pending. The DLL has not written yet. The honest answer is the run
        #     directory's not-yet-existing path: the caller reads nothing and waits.
        check(
            resolved(name) == str(run_dir / name),
            "reader, redirect pending: resolves to this run's path, which does not exist yet",
        )
        # (2) stale only. The game directory holds the previous run's file and nothing else.
        #     Returning it would score an ended run as this one -- the measured teardown bug.
        write(game_dir / name, '{"escaped_write_site_count": 3}\n', stale)
        check(
            resolved(name) == str(run_dir / name),
            "reader, stale only: the PREVIOUS run's game-directory file is refused, not read",
        )
        # (3) ENV lost. The redirect did not survive me3 -> Proton, so the DLL fell back to the
        #     game directory -- and that file is this run's, by its mtime. Ignoring it would
        #     report a healthy run as silent, which reads exactly like a broken feature.
        write(game_dir / name, '{"escaped_write_site_count": 0}\n', fresh)
        check(
            resolved(name) == str(game_dir / name),
            "reader, env-lost fallback: a game-directory file newer than the launch IS this run's",
        )
        # (4) redirect live. Once the run directory has it, it wins outright.
        write(run_dir / name, '{"escaped_write_site_count": 0}\n', fresh)
        check(
            resolved(name) == str(run_dir / name),
            "reader, redirect live: the run directory wins over the game directory",
        )
        # Non-VACUITY on the floor itself: drop `newer_than` and state (2) silently returns the
        # previous run's verdict. That is the whole bug, so the check must be able to fail.
        (run_dir / name).unlink()
        write(game_dir / name, '{"escaped_write_site_count": 3}\n', stale)
        check(
            resolve_artifact(name, game_dir, prefer=run_dir) == game_dir / name
            and resolve_artifact(name, game_dir, prefer=run_dir, newer_than=launch)
            == run_dir / name,
            "...and WITHOUT the mtime floor the same call returns the previous run's file",
        )

    print("selftest:", "PASS" if ok else "FAIL")
    return EXIT_OK if ok else EXIT_GAP


def print_table(knobs: list[Knob], launchers: list[Launcher]) -> None:
    rows = inventory_rows(knobs)
    width = max(len(row[0]) for row in rows)
    # Measured, not guessed: a fixed width silently ragged the table the moment a knob name grew
    # past it, and a report whose columns do not line up gets skimmed instead of read.
    knob_width = max(len("redirect knob"), max(len(row[2]) for row in rows))
    print("PER-RUN ARTIFACTS -- what a run writes, and what happens to the run before it")
    print()
    print(f"  {'artifact'.ljust(width)}  {'redirect knob'.ljust(knob_width)}  kept in GAME_DIR  rotation")
    print(f"  {'-' * width}  {'-' * knob_width}  ----------------  --------")
    for artifact, _source, knob, rotation, kept in rows:
        print(f"  {artifact.ljust(width)}  {knob.ljust(knob_width)}  {kept:^16}  {rotation}")
    print()
    print("  'kept in GAME_DIR' is how many PREVIOUS runs survive there: 1 means `<name>.prev`")
    print("  holds the run immediately before the live file and nothing older; 0 means the")
    print("  previous run is gone the moment this one starts. A harness `rm -f` of the live file")
    print("  before launch takes the `.prev` with it, so both numbers become 0.")
    print()
    print("LAUNCHERS")
    print()
    wanted = {knob.env for knob in knobs}
    for launcher in sorted(launchers, key=lambda item: item.name):
        if launcher.is_library:
            print(f"  {launcher.name}: library -- the caller owns the redirect")
            continue
        if launcher.single_slot:
            print(f"  {launcher.name}: SINGLE-SLOT BY DESIGN -- {launcher.single_slot}")
            print(f"      all {len(wanted)} artifacts stay beside eldenring.exe; the run before")
            print("      last is gone. Stated, not fixed.")
            continue
        if launcher.delegates_to:
            print(f"  {launcher.name}: delegates to {launcher.delegates_to}")
            continue
        missing = sorted(wanted - launcher.sets - set(launcher.exempt))
        state = "redirects everything" if not missing else f"MISSING {len(missing)}"
        print(f"  {launcher.name}: {state}")
        for env in missing:
            print(f"      missing  {env}")
        for env, reason in sorted(launcher.exempt.items()):
            print(f"      exempt   {env} -- {reason}")


BASELINE = SCRIPTS / "er-artifact-redirect-audit.baseline.txt"

BASELINE_HEADER = """\
# LAUNCHERS THAT STILL LEAK A PER-RUN ARTIFACT INTO THE GAME DIRECTORY.
#
# This is a TO-DO LIST, not an approval. Every line is a run whose evidence the NEXT launch can
# destroy -- a game-directory artifact is single-slot, and two launches lose the run before last.
# It exists so the audit can fail on NEW drift while the known backlog stays written down and
# counted instead of silently tolerated.
#
# To clear a line: set that env var, in that launcher, to a path inside the run's own artifact
# directory, then delete the line (or re-run with --write-baseline).
#
# One `<launcher> <ENV_VAR>` per line. Regenerate with:
#     python3 scripts/er-artifact-redirect-audit.py --write-baseline
#
# EMPTY SINCE 2026-08-31 -- 98 rows across 13 launchers, all closed. An empty file is not the same
# as no gate: `--selftest` requires the STRICT audit (which ignores this file entirely) to agree
# that nothing leaks, so emptiness has to be earned rather than assumed.
"""


def gap_keys(knobs: list[Knob], launchers: list[Launcher]) -> list[str]:
    """`<launcher> <ENV>` for every undeclared gap -- the baseline's line format."""
    wanted = {knob.env for knob in knobs}
    keys = []
    for launcher in launchers:
        if launcher.is_library or launcher.delegates_to or launcher.single_slot:
            continue
        for env in sorted(wanted - launcher.sets - set(launcher.exempt)):
            keys.append(f"{launcher.name} {env}")
    return sorted(keys)


def read_baseline() -> set[str]:
    if not BASELINE.is_file():
        return set()
    return {
        line.strip()
        for line in BASELINE.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", action="store_true", help="print the artifact inventory")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="fail on EVERY gap, ignoring the recorded backlog in the baseline file",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="record today's gaps as the accepted backlog (they are still gaps)",
    )
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return selftest()

    knobs = discover_knobs()
    if not knobs:
        print(
            "er-artifact-redirect-audit: found NO redirect knobs in the Rust sources. That is a "
            "broken audit, not a clean tree.",
            file=sys.stderr,
        )
        return EXIT_BROKEN
    launchers = discover_launchers()

    if args.table:
        print_table(knobs, launchers)
        return EXIT_OK

    keys = gap_keys(knobs, launchers)
    if args.write_baseline:
        BASELINE.write_text(BASELINE_HEADER + "\n".join(keys) + "\n", encoding="utf-8")
        print(f"er-artifact-redirect-audit: recorded {len(keys)} known gap(s) in {BASELINE}")
        return EXIT_OK

    baseline = set() if args.strict else read_baseline()
    stale_rows = (
        verify_no_knob_table()
        + verify_recovered_knobs(knobs)
        + verify_shared_table(knobs)
    )
    delegation = [
        problem for problem in audit(knobs, launchers) if "delegates-to" in problem
    ]
    new_gaps = [key for key in keys if key not in baseline]
    resolved = sorted(baseline - set(keys))

    # The backlog is printed even when it passes. A gate that says "ok" while 40 launchers still
    # write into a directory the next launch clears is the exact silence this audit was written to
    # break: it would read as "we captured everything".
    carried = sorted(key for key in keys if key in baseline)
    if carried:
        print(
            f"er-artifact-redirect-audit: {len(carried)} KNOWN gap(s) still open across "
            f"{len({key.split()[0] for key in carried})} launcher(s) -- recorded in "
            f"{BASELINE.name}, NOT fixed:"
        )
        for key in carried:
            print(f"  {key}")
        print()

    problems = stale_rows + delegation
    for key in new_gaps:
        launcher_name, env = key.split()
        problems.append(
            f"{launcher_name}: does not redirect {env}; that artifact stays in GAME_DIR, where "
            f"the next launch destroys it. Set it to a path inside this run's artifact dir, or "
            f"declare `# {MARKER} exempt {env} -- <reason>`."
        )
    if problems:
        print("er-artifact-redirect-audit: undeclared per-run artifact gaps\n", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        print(
            f"\n{len(problems)} gap(s). A GAME_DIR artifact is single-slot: the next launch "
            f"destroys it, and a copy at teardown cannot recover what this run already clobbered.",
            file=sys.stderr,
        )
        return EXIT_GAP

    if resolved:
        print(
            f"{len(resolved)} baseline entr(y/ies) no longer leak; drop them with "
            f"--write-baseline: {', '.join(resolved)}"
        )
    # Printed on success, like the backlog above, and for the same reason. A stated single-slot
    # launcher is not a clean one: its runs still overwrite each other beside `eldenring.exe`. It
    # was invisible here until 2026-08-31 -- absent from the report entirely, which reads as
    # compliance rather than as a decision somebody made.
    stated = [launcher for launcher in launchers if launcher.single_slot]
    for launcher in sorted(stated, key=lambda item: item.name):
        print(
            f"er-artifact-redirect-audit: {launcher.name} is SINGLE-SLOT BY DESIGN -- "
            f"{launcher.single_slot}"
        )
    print(
        f"er-artifact-redirect-audit: {len(launchers)} launcher(s), {len(knobs)} knob(s), "
        f"{len(stated)} stated single-slot, no NEW gaps"
    )
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
