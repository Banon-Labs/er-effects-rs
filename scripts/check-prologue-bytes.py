def selftest() -> int:
    failures: list[str] = []
    for label, expected, files in SELFTEST_CASES:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for relative, body in files.items():
                target = root / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(body, encoding="utf-8")
            found = scan(root)
            if len(found) != expected:
                failures.append(
                    f"{label}: expected {expected} finding(s), got {len(found)}: "
                    + ", ".join(f"{item.path}:{item.line} {item.name}" for item in found)
                )
    if failures:
        print("check-prologue-bytes selftest FAILED:", file=sys.stderr)
        for failure in failures:
            print(f"  {failure}", file=sys.stderr)
        return 1
    print(f"check-prologue-bytes selftest passed ({len(SELFTEST_CASES)} cases)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--selftest", action="store_true", help=selftest.__doc__)
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    arguments = parser.parse_args()
    if arguments.selftest:
        return selftest()
    findings = scan(arguments.root.resolve())
    if findings:
        report(findings)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
