# --- image / matching primitives --------------------------------------------------------------
class Image:
    """A flat (virtual-layout) PE image: file offset == RVA, VA == base + offset."""

    def __init__(self, path: Path):
        self.path = path
        self.data = path.read_bytes()
        pe = struct.unpack_from("<I", self.data, 0x3C)[0]
        if self.data[pe : pe + 4] != b"PE\0\0":
            raise SystemExit(f"{path}: not a PE image")
        nsec = struct.unpack_from("<H", self.data, pe + 6)[0]
        optsz = struct.unpack_from("<H", self.data, pe + 20)[0]
        off = pe + 24 + optsz
        self.text = []  # every section named .text, in table order
        self.sections = {}
        for i in range(nsec):
            entry = self.data[off + i * 40 : off + (i + 1) * 40]
            name = entry[:8].rstrip(b"\0").decode("latin1")
            vsz, va, rsz, _raw = struct.unpack_from("<IIII", entry, 8)
            span = (va, max(vsz, rsz))
            self.sections.setdefault(name, span)
            if name == ".text":
                self.text.append(span)
        self._funcs = None

    def functions(self):
        """`.pdata` function extents as a sorted list of (begin_rva, end_rva)."""
        if self._funcs is None:
            va, size = self.sections[".pdata"]
            seen = {}
            for off in range(va, va + size, 12):
                begin, end, _unwind = struct.unpack_from("<III", self.data, off)
                if begin == 0 or end <= begin or end - begin > 0x20000:
                    continue
                seen.setdefault(begin, end)
            self._funcs = sorted(seen.items())
        return self._funcs

    def containing(self, rva):
        """(begin, end) of the `.pdata` function containing `rva`, or None."""
        funcs = self.functions()
        starts = [f[0] for f in funcs]
        i = bisect.bisect_right(starts, rva) - 1
        if i < 0:
            return None
        begin, end = funcs[i]
        return (begin, end) if rva < end else None


def parse_sig(sig):
    """IDA-style signature -> (bytes, mask). `?` and `??` are wildcards."""
    want, mask = [], []
    for token in sig.split():
        if token in ("?", "??"):
            want.append(0)
            mask.append(False)
        else:
            want.append(int(token, 16))
            mask.append(True)
    if not want:
        raise ValueError("empty signature")
    if not any(mask):
        raise ValueError("signature is entirely wildcards")
    return bytes(want), mask


def find_all(data, start, size, want, mask, cap=4096):
    """Every offset in [start, start+size) matching (want, mask), overlapping matches included."""
    n = len(want)
    anchor = next(i for i, keep in enumerate(mask) if keep)
    needle = bytes([want[anchor]])
    hits = []
    end = start + size
    cursor = start
    while len(hits) < cap:
        at = data.find(needle, cursor, end)
        if at < 0:
            break
        off = at - anchor
        cursor = at + 1
        if off < start or off + n > end:
            continue
        if all(not mask[j] or data[off + j] == want[j] for j in range(n)):
            hits.append(off)
    return hits


# --- source extraction (the anti-drift half) --------------------------------------------------
_STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def extract_literals(path, symbol):
    """Every string literal in the initialiser of `const`/`static` `symbol` in `path`."""
    src = path.read_text(encoding="utf-8", errors="replace")
    decl = re.search(
        r"(?:const|static)\s+" + re.escape(symbol) + r"\s*:", src
    )
    if not decl:
        raise KeyError(f"{path}: no const/static named {symbol}")
    # The initialiser runs to the first `;` at nesting depth 0 after the `=`.
    eq = src.index("=", decl.end())
    depth = 0
    i = eq
    while i < len(src):
        ch = src[i]
        if ch == '"':  # skip a string literal wholesale
            m = _STRING.match(src, i)
            i = m.end() if m else i + 1
            continue
        if ch in "[({":
            depth += 1
        elif ch in "])}":
            depth -= 1
        elif ch == ";" and depth == 0:
            break
        i += 1
    return [m.group(1) for m in _STRING.finditer(src[eq:i])]


def check_sync():
    """Every pinned pattern still matches the literal in its source file."""
    bad = 0
    print("== sync: pinned literals vs. the crates they live in ==")
    for entry in REGISTRY:
        path = ROOT / entry["source"]
        try:
            literals = extract_literals(path, entry["symbol"])
        except (KeyError, OSError, ValueError) as exc:
            print(f"  DRIFT {entry['id']}: {exc}")
            bad += 1
            continue
        for index in entry["literals"]:
            if index >= len(literals):
                print(
                    f"  DRIFT {entry['id']}: {entry['symbol']} has {len(literals)} literal(s), "
                    f"wanted index {index}"
                )
                bad += 1
                continue
            if literals[index] != entry["pattern"]:
                print(f"  DRIFT {entry['id']}: source says\n      {literals[index]}\n    pin says\n      {entry['pattern']}")
                bad += 1
            else:
                print(f"  ok    {entry['id']}  ({entry['symbol']}[{index}] in {entry['source']})")
    return bad


# --- classification ---------------------------------------------------------------------------
def classify(n_1162, n_1170):
    if n_1162 == 1 and n_1170 == 1:
        return "UNIQUE-BOTH"
    if n_1170 == 0:
        return "ZERO-ON-1170"
    if n_1162 == 1 and n_1170 > 1:
        return "MULTI-ON-1170"
    if n_1162 > 1 and n_1170 == n_1162:
        return "MULTI-BOTH-EQUAL"
    if n_1162 > 1:
        return "MULTI-BOTH-DIFFERENT"
    if n_1162 == 0:
        return "ZERO-ON-1162"
    return "UNCLASSIFIED"


def correspondence(images, hits):
    """Do the 1.16.2 and 1.17 hit lists describe the same sites?

    Each hit is reduced to its offset inside the `.pdata` function that contains it.  A function
    that moved without changing produces the identical offset; a hit that landed somewhere new
    does not.  The containing function's extent is reported separately rather than folded into
    the identity, because a function can grow by a few bytes -- 1.17 added 8 bytes to
    `0x140af7cf0` -- while every hit inside it stays at the same offset.  Requiring equal extents
    reported that as five disagreements when nothing had moved.
    """
    reduced = {}
    for build in ("1162", "1170"):
        image = images[build]
        rows = []
        for hit in hits[build]:
            span = image.containing(hit)
            rows.append(None if span is None else (hit - span[0], span[1] - span[0]))
        reduced[build] = rows
    if len(reduced["1162"]) != len(reduced["1170"]):
        return "counts differ", reduced
    total = len(reduced["1162"])
    if total == 0:
        return "no hits to correspond", reduced
    pairs = list(zip(reduced["1162"], reduced["1170"]))
    same_off = sum(1 for a, b in pairs if a is not None and b is not None and a[0] == b[0])
    grew = sum(1 for a, b in pairs if a is not None and b is not None and a[1] != b[1])
    detail = f"{same_off}/{total} at the same offset inside their function"
    if grew:
        detail += f" ({grew} of those functions changed size)"
    return detail, reduced


def run_patterns(require_images):
    missing = [b for b, p in IMAGES.items() if not p.is_file()]
    if missing:
        line = ", ".join(f"{b} ({IMAGES[b]})" for b in missing)
        print(f"== patterns: SKIPPED -- missing image(s): {line}")
        return 1 if require_images else 0
    images = {b: Image(p) for b, p in IMAGES.items()}
    print("== patterns: literal AOB signatures over the runtime-scanned .text ==")
    for build, image in images.items():
        primary, tail = image.text[0], image.text[1] if len(image.text) > 1 else None
        note = (
            f"  tail .text {BASE + tail[0]:#x}+{tail[1]:#x} (Arxan; NOT scanned at runtime)"
            if tail
            else ""
        )
        print(f"  [{build}] runtime .text {BASE + primary[0]:#x}+{primary[1]:#x}{note}")
    bad = 0
    for entry in REGISTRY:
        want, mask = parse_sig(entry["pattern"])
        hits = {}
        for build, image in images.items():
            start, size = image.text[0]
            hits[build] = find_all(image.data, start, size, want, mask)
        n = {b: len(v) for b, v in hits.items()}
        verdict = classify(n["1162"], n["1170"])
        pinned = entry["expect"]
        drift = n["1162"] != pinned["1162"] or n["1170"] != pinned["1170"]
        corr, _ = correspondence(images, hits)
        print(f"\n  {entry['id']}  [{entry['consumer']}]  {len(want)} bytes")
        print(f"    1.16.2 hits={n['1162']:<5d} 1.17 hits={n['1170']:<5d} -> {verdict}")
        print(f"    correspondence: {corr}")
        show = ", ".join(hex(BASE + h) for h in hits["1170"][:4])
        print(f"    1.17 first hits: {show or '(none)'}")
        print(f"    {entry['note']}")
        if drift:
            print(
                f"    REGRESSION: pinned {pinned['1162']}/{pinned['1170']}, "
                f"measured {n['1162']}/{n['1170']}"
            )
            bad += 1
        if verdict in ("MULTI-ON-1170", "MULTI-BOTH-DIFFERENT"):
            bad += 1
        if verdict == "ZERO-ON-1170" and entry["consumer"] != "unique-or-refuse":
            bad += 1
    return bad


# --- needle audit -----------------------------------------------------------------------------
_TABLES = None


def translation_tables():
    """`(call, detour)` -- the two maps `er-game-base/build.rs` emits, as `{rva: rva}`.

    The ledger is four files, not two.  `emit_address_map` reads `VERIFIED_MAP`,
    `NEEDED_VERIFIED_MAP`, `FUNCTION_MAP` and `DATA_MAP`, applies a verdict/instruction-count/
    entry-evidence admission rule to the two verdict tables, and subtracts a quarantine and every
    `DIVERGES` row.  This function used to read two of those four files raw, and the cost was not
    a rounding error: 36 of its 37 `NO-ROW` verdicts were wrong.  `NO-ROW` reads as "safe --
    `er-hook` refuses the address before any byte check runs", so 36 pins whose hook does install
    on 1.17 were reported as inert, and one of them (`WorldMapAreaConverter::
    ConvertMsbCoordsToMapCoords`) actually DISARMS on 1.17.  A real finding, in a green gate,
    reported as nothing.  Measured 2026-08-30.

    The rules are not copied here.  `check-1170-translation-collisions.py` parses them out of
    `build.rs` itself, and its output was confirmed byte-identical to the `address_map_1170.rs`
    cargo generated (476 call rows, 372 detour rows).  If `build.rs` moves in a way that gate
    cannot parse it raises `Refuse`, and that propagates rather than falling back to the partial
    read -- a partial read is the failure this replaced.
    """
    global _TABLES
    if _TABLES is None:
        tables = _COLLISIONS.emit(_COLLISIONS.build_rules())
        _TABLES = (
            {row.src: row.dst for row in tables[_COLLISIONS.CALL]},
            {row.src: row.dst for row in tables[_COLLISIONS.DETOUR]},
        )
    return _TABLES


def ledger_rvas():
    """Every 1.16.2 RVA the shipped call map translates. See `translation_tables`."""
    return translation_tables()[0]


def detour_rvas():
    """The subset carrying detour evidence too. A call-only row cannot carry a hook."""
    return translation_tables()[1]


