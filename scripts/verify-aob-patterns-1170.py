#!/usr/bin/env python3
"""Re-validate every runtime byte-signature / AOB scan pattern against ELDEN RING 1.17.

Why this exists
---------------
A hardcoded RVA that moved gets refused by `er-game-base`'s translation gate: loud, safe, one
missing feature.  A scan has no such gate.  It runs against whatever image is loaded and answers
with an address, and there are three ways that answer goes wrong:

  (a) it matches nothing          -> the feature is refused.  Loud and safe.
  (b) it matches a different site -> a confident wrong address that reads as a live value.
  (c) it matches more than once where it used to be unique -> "first match wins" picks silently.

Only (a) is safe, and a bare 1.17 hit count cannot tell the three apart.  The 1.16.2 count is the
CALIBRATION: a pattern that was already non-unique on the image it was authored against was
fragile before 1.17 touched it, and its 1.17 count means nothing without that context.

A scan result is already a 1.17 address.  It must never be put through the 1.16.2 -> 1.17
translator -- doing that translates a correct address a second time.  That nearly shipped two
crash-hooking rows for `er-armament-icons` (a +0x1e00 jump into mid-function); see the removal
note in `docs/recon/rva-map-1162-to-1170.verified.tsv`.

What it checks
--------------
  patterns  Every literal AOB in the tree, scanned over both images' first `.text` (which is the
            section the runtime scanners bound themselves to -- see NOTE on `.text` below), with
            the hits classified and, where the counts agree, checked for 1:1 correspondence by
            `.pdata` function containment.
  needles   The other scan family: pointer-value scans whose needle is built at runtime from an
            RVA constant.  `er_game_base::mem::game_data_addr` answers **0** for an address with
            no verified 1.17 mapping.  A refusal used as a DEREFERENCE target is safe (the read
            faults closed).  A refusal used as a scan needle is the opposite of safe: zero matches
            every zeroed qword in the address space, so the scan returns a confident pointer into
            blank memory.  This section reports, per scan, whether the needle RVA has a ledger row
            and whether the code rejects a zero needle.
  prologues The other runtime byte-signature family: the detour-prologue constants generated by
            `build-support/prologue_build.rs`.  These are not scans -- each is checked at one
            address -- but they are still 1.16.2 bytes compared against live memory, and they
            decide whether a hook arms.  Each is re-checked against the 1.17 image at the address
            the RVA ledger maps it to, so the report says which features the gate will disarm.
  sync      Every pinned pattern literal is re-extracted from the source file it lives in.  This
            is what keeps the answer regenerable instead of a snapshot: edit the constant in the
            crate and this fails until the pin is updated.

`sync` needs no game image and always runs.  `patterns` skips when an image is missing (the same
shape as the corpus-gated tests), unless `--require-images` is passed.

NOTE on `.text`
---------------
Both images carry two sections named `.text`: the real code at 0x140001000, and an Arxan tail at
the very top of the image.  Every runtime scanner in this repo resolves the section by walking the
PE section table and returning the first `.text` (`er_game_base::mem::module_text_range`, and
`find_text_section` in er-quickload's crashlog), so that is the range scanned here.  The tail is
reported separately and is informational only.

Usage
    python3 scripts/verify-aob-patterns-1170.py                 # everything
    python3 scripts/verify-aob-patterns-1170.py --section needles
    python3 scripts/verify-aob-patterns-1170.py --section prologues
    python3 scripts/verify-aob-patterns-1170.py --selftest
    python3 scripts/verify-aob-patterns-1170.py --require-images

Exit code 0 = every pattern matched its pinned classification and every needle scan is accounted
for; 1 = a drift, a regression, or an unguarded scan whose needle has no 1.17 mapping.
"""

